"""`veklom-gate-init`: write a ready-to-run .env with fresh secrets, read-only by default."""
from __future__ import annotations

import argparse
import os
import re
import secrets
import socket
import sys
from pathlib import Path
from urllib.parse import urlparse

AUDIENCE = re.compile(r"^[a-z0-9][a-z0-9._-]{1,62}$")


def detect_socket_gid(path: str = "/var/run/docker.sock") -> int | None:
    try:
        return os.stat(path).st_gid
    except OSError:
        return None


def _url(value: str | None, label: str) -> str:
    if not value:
        return ""
    parsed = urlparse(value)
    if parsed.scheme not in {"http", "https"} or not parsed.netloc:
        raise SystemExit(f"{label} must be a full http(s) URL, got {value!r}")
    return value.rstrip("/") if label == "--public-url" else value


def render_env(*, audience: str, public_url: str, approver_url: str, socket_gid: int, allowed_host: str) -> str:
    access, gate_read, gate_act = (secrets.token_urlsafe(32) for _ in range(3))
    return f"""# Generated by veklom-gate-init. Keep this file out of Git; it contains secrets.
# Starts READ-ONLY: the agent can look but not touch. Enable actions in step 3 of the quick start.

# --- MCP server --------------------------------------------------------------
VEKLOM_MCP_ENVIRONMENT=production
# Give this to your MCP client as: Authorization: Bearer <token>
VEKLOM_MCP_ACCESS_TOKEN={access}
VEKLOM_MCP_WRITES_ENABLED=false
VEKLOM_MCP_APPROVAL_AUDIENCE={audience}
# Paste the public key shown by the approver page ("Make this device an approver").
VEKLOM_MCP_APPROVAL_PUBLIC_KEY_B64=
VEKLOM_MCP_APPROVER_URL={approver_url}
VEKLOM_MCP_PUBLIC_URL={public_url}
MCP_ALLOWED_HOSTS={allowed_host}
VEKLOM_MCP_PROFILE=generic
VEKLOM_MCP_HEALTH_TARGETS=

# --- Docker gate (the only container that holds the Docker socket) ----------
DOCKER_GATE_READ_TOKEN={gate_read}
DOCKER_GATE_ACT_TOKEN={gate_act}
DOCKER_GATE_ALLOW_ACT=false
DOCKER_GATE_MANAGED_LABEL=veklom.ops.managed=true
DOCKER_SOCKET_GID={socket_gid}

# --- Cloudflare Tunnel (optional; deploy/cloudflare-tunnel.yml) --------------
CLOUDFLARE_TUNNEL_TOKEN=
"""


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Create a Veklom Gate .env with fresh random secrets (read-only by default).")
    parser.add_argument("--audience", default=None, help="Unique name for this deployment (default: this host's name).")
    parser.add_argument("--public-url", default=None, help="Public URL of this MCP server, e.g. https://ops.example.com")
    parser.add_argument("--approver-url", default=None, help="Where the approver page is hosted, e.g. https://approve.example.com/")
    parser.add_argument("--socket-gid", type=int, default=None, help="Group id of /var/run/docker.sock (auto-detected when possible).")
    parser.add_argument("--out", default=".env")
    parser.add_argument("--force", action="store_true", help="Overwrite an existing file.")
    args = parser.parse_args(argv)

    audience = (args.audience or socket.gethostname()).strip().lower()
    if not AUDIENCE.match(audience):
        raise SystemExit("--audience must be 2-63 chars of a-z, 0-9, '.', '_' or '-' (e.g. acme-prod)")
    public_url = _url(args.public_url, "--public-url")
    approver_url = _url(args.approver_url, "--approver-url")
    if public_url and approver_url and urlparse(public_url).netloc == urlparse(approver_url).netloc:
        raise SystemExit("--approver-url must be a different host from --public-url (see SECURITY.md).")
    gid = args.socket_gid if args.socket_gid is not None else detect_socket_gid()
    if gid is None:
        raise SystemExit("Could not read /var/run/docker.sock here; pass --socket-gid \"$(stat -c %g /var/run/docker.sock)\"")

    out = Path(args.out)
    if out.exists() and not args.force:
        raise SystemExit(f"{out} already exists; pass --force to replace it (its secrets will change).")
    out.write_text(
        render_env(
            audience=audience,
            public_url=public_url,
            approver_url=approver_url,
            socket_gid=gid,
            allowed_host=urlparse(public_url).hostname or "" if public_url else "",
        ),
        encoding="utf-8",
    )
    try:
        out.chmod(0o600)
    except OSError:
        pass
    print(f"Wrote {out} for deployment '{audience}' (read-only; secrets generated).", file=sys.stderr)
    print("Next: label containers with veklom.ops.managed=true, then `docker compose up -d`.", file=sys.stderr)


if __name__ == "__main__":
    main()
